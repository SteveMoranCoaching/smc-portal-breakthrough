
"use client"

import { useEffect, useRef, useState } from "react"

type Props = {
  fileId: string
  mediaType: "image" | "video"
  filename: string
}

export default function MediaThumbnail({
  fileId,
  mediaType,
  filename,
}: Props) {
  const containerRef = useRef<HTMLDivElement>(null)

  const [isVisible, setIsVisible] = useState(false)
  const [imageUrl, setImageUrl] = useState<string | null>(null)
  const [failed, setFailed] = useState(false)

  useEffect(() => {
    const element = containerRef.current

    if (!element) return

    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setIsVisible(true)
          observer.disconnect()
        }
      },
      {
        rootMargin: "150px",
      }
    )

    observer.observe(element)

    return () => observer.disconnect()
  }, [])

  useEffect(() => {
    if (!isVisible || mediaType !== "image") return

    let cancelled = false

    async function loadThumbnail() {
      try {
        const response = await fetch(
          "/api/coach/media/preview",
          {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
            },
            body: JSON.stringify({ fileId }),
          }
        )

        const result = await response.json()

        if (!response.ok || typeof result.url !== "string") {
          throw new Error("Unable to load thumbnail.")
        }

        if (!cancelled) {
          setImageUrl(result.url)
        }
      } catch {
        if (!cancelled) {
          setFailed(true)
        }
      }
    }

    void loadThumbnail()

    return () => {
      cancelled = true
    }
  }, [fileId, isVisible, mediaType])

  return (
    <div
      ref={containerRef}
      className="relative flex aspect-square min-w-0 w-full items-center justify-center overflow-hidden rounded-lg border border-white/[0.06] bg-[#111]"
    >
      {mediaType === "video" ? (
        <div className="flex flex-col items-center gap-2 text-white/40">
          <span className="text-4xl">🎬</span>
          <span className="text-[10px] font-black uppercase tracking-widest">
            Video
          </span>
        </div>
      ) : imageUrl && !failed ? (
        // Signed URLs are generated by the authenticated coach API.
        // eslint-disable-next-line @next/next/no-img-element
        <img
          src={imageUrl}
          alt={filename}
          loading="lazy"
          onError={() => setFailed(true)}
          className="absolute inset-0 block h-full w-full min-w-0 object-cover transition duration-300 group-hover:scale-[1.03]"
        />
      ) : failed ? (
        <div className="flex flex-col items-center gap-2 text-white/30">
          <span className="text-3xl">🖼️</span>
          <span className="text-[10px]">
            Preview unavailable
          </span>
        </div>
      ) : (
        <div className="flex flex-col items-center gap-2 text-white/30">
          <span className="animate-pulse text-3xl">🖼️</span>
          <span className="text-[10px]">
            Loading preview...
          </span>
        </div>
      )}
    </div>
  )
}
